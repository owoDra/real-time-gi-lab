#!/usr/bin/env python3
"""Generate the N009 CPU-only frame-state exporter header by VERBATIM extraction.

Same method as N008 (its unchanged `extract` and N001 item list are imported):
the A001 V3 helpers, the renamed original build_a001_params and the N009 C1
wrapper are extracted from the GENERATED n009_a001_runtime.cpp, so the exporter
and the N009 GPU capture compile the same parameter code."""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "n008_hdr_oracle"))
import generate_state_exporter as n008  # noqa: E402  (N008, unchanged)

A001_ITEMS = n008.A001_ITEMS[:-1] + [
    r"A001ParamsGpu n009_a001_original_build_a001_params\(const SceneSurfaceSet& scene, const A001Settings& settings\) \{",
    r"A001ParamsGpu build_a001_params\(const SceneSurfaceSet& scene, const A001Settings& settings\) \{",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--a001-runtime", required=True, help="generated n009_a001_runtime.cpp")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    root = Path(a.root)
    n001 = (root / n008.N001).read_text()
    n002 = (root / n008.N002).read_text()
    a001 = Path(a.a001_runtime).read_text()
    norm = [l.strip() for l in n002.splitlines()]
    for line in n008.N002_LINES:
        if line not in norm:
            raise SystemExit(f"N002 churn line drifted: {line!r}")
    sha = {n008.N001: hashlib.sha256((root / n008.N001).read_bytes()).hexdigest(),
           n008.N002: hashlib.sha256((root / n008.N002).read_bytes()).hexdigest(),
           "generated/n009_a001_runtime.cpp": hashlib.sha256(Path(a.a001_runtime).read_bytes()).hexdigest()}
    parts = ["// GENERATED by scripts/research/n009_scene_contract/generate_state_exporter.py -- do not edit.",
             "#pragma once", '#include "n009_contract.hpp"']
    parts += [f"// source {p} sha256 {h}" for p, h in sha.items()]
    parts.append("namespace n009_extracted_a001 {\nusing namespace phos::gi::lane_a;")
    parts += [n008.extract(a001, x) for x in A001_ITEMS]
    parts.append("}  // namespace n009_extracted_a001")
    parts.append("namespace n009_extracted_n001 {\nnamespace lane_a = phos::gi::lane_a;\n"
                 "namespace lane_b = phos::gi::research::lane_b;")
    parts += [n008.extract(n001, x) for x in n008.N001_ITEMS]
    parts.append("}  // namespace n009_extracted_n001")
    parts.append("inline constexpr const char* kN009ExtractedSources[][2] = {" +
                 ", ".join(f'{{"{p}", "{h}"}}' for p, h in sha.items()) + "};")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
