#!/usr/bin/env python3
"""N009 fail-closed build overlays for scene contract C1 + back-face rule BF-P.

Generates N009-only copies of three pinned N-series sources; the originals and
the default build graph are untouched:
  a001_scene.cpp   -> n009_a001_scene.cpp   (glTF node world transforms)
  b002_scene.cpp   -> n009_b002_scene.cpp   (node transforms; BF-P: two_sided=true)
  a001_runtime.cpp -> n009_a001_runtime.cpp (authored camera + contract light)
Each edit must match exactly once, so pinned-source drift fails the build.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

SRC = "src/research/lane_n_end_to_end_renderer/imported"
FILES = {
    "n009_a001_scene.cpp": f"{SRC}/lane_a_split_rc/a001_scene.cpp",
    "n009_b002_scene.cpp": f"{SRC}/lane_b_traversal/b002_scene.cpp",
    "n009_a001_runtime.cpp": f"{SRC}/lane_a_split_rc/a001_runtime.cpp",
}


def exactly_one(source: str, old: str, new: str) -> str:
    n = source.count(old)
    if n != 1:
        raise ValueError(f"N009 source contract drift: expected one, found {n}: {old[:90]!r}")
    return source.replace(old, new)


def header(text: str, origin: str, sha: str) -> str:
    return (f"// GENERATED by scripts/research/n009_scene_contract/generate_overlay.py from\n"
            f"// {origin} (sha256 {sha}) -- N009 opt-in overlay, do not edit.\n" + text)


def a001_scene(s: str) -> str:
    s = exactly_one(s, '#include "a001_scene.hpp"', '#include "a001_scene.hpp"\n#include "n009_contract.hpp"')
    s = exactly_one(s, "    auto out = begin_set();\n    for (const auto& mesh : asset.meshes) {",
                    "    const auto n009_world = n009::mesh_world_transforms(asset);\n"
                    "    auto out = begin_set();\n"
                    "    for (std::size_t n009_mesh = 0; n009_mesh < asset.meshes.size(); ++n009_mesh) {\n"
                    "        const auto& mesh = asset.meshes[n009_mesh];")
    s = exactly_one(s, "[&](fastgltf::math::fvec3 p, std::size_t i) { positions[i] = p; });",
                    "[&](fastgltf::math::fvec3 p, std::size_t i) {\n"
                    "                    positions[i] = n009::apply(n009_world[n009_mesh], p);\n"
                    "                });")
    return s


def b002_scene(s: str) -> str:
    s = exactly_one(s, '#include "b002_scene.hpp"', '#include "b002_scene.hpp"\n#include "n009_contract.hpp"')
    s = exactly_one(s, "    B002Scene scene;\n    for (std::size_t mesh_index = 0;",
                    "    const auto n009_world = n009::mesh_world_transforms(asset);\n"
                    "    B002Scene scene;\n    for (std::size_t mesh_index = 0;")
    s = exactly_one(s, "                    positions[index] = position;",
                    "                    positions[index] = n009::apply(n009_world[mesh_index], position);")
    # BF-P: every triangle is an opaque two-sided surface for every ray type.
    s = exactly_one(s, "            bool two_sided = false;",
                    "            bool two_sided = true;  // N009 BF-P (doubleSided ignored)")
    s = exactly_one(s, "                two_sided = asset.materials[value].doubleSided;",
                    "                (void)asset.materials[value].doubleSided;  // N009 BF-P")
    return s


def a001_runtime(s: str) -> str:
    s = exactly_one(s, '#include "a001_runtime.hpp"', '#include "a001_runtime.hpp"\n#include "n009_contract.hpp"')
    sig = "A001ParamsGpu build_a001_params(const SceneSurfaceSet& scene, const A001Settings& settings) {"
    s = exactly_one(s, sig, "A001ParamsGpu n009_a001_original_build_a001_params(const SceneSurfaceSet& scene, const A001Settings& settings) {")
    anchor = "struct A001Runtime::Impl {"
    wrapper = (
        "// N009 contract C1: an authored glTF camera replaces the A001 orbit camera and\n"
        "// the preregistered contract light replaces the A001 light. Near/far, probe\n"
        "// spacing, light interval scale and limits keep the A001 bounds formulas.\n"
        "A001ParamsGpu build_a001_params(const SceneSurfaceSet& scene, const A001Settings& settings) {\n"
        "    A001ParamsGpu p=n009_a001_original_build_a001_params(scene,settings);\n"
        "    const auto& cam=n009::authored_camera();\n"
        "    if(!cam.present) return p;\n"
        "    const auto& k=n009::contract();\n"
        "    const bool moved=settings.case_id==A001Case::CameraMotion;\n"
        "    const float tan_y=std::tan(cam.yfov*0.5f);\n"
        "    for(int i=0;i<3;++i){\n"
        "        p.camera_pos_near[i]=cam.eye[i]+(moved?k.camera_motion_offset[i]:0.0f);\n"
        "        p.camera_right_tan_x[i]=cam.right[i];\n"
        "        p.camera_up_tan_y[i]=cam.up[i];\n"
        "        p.camera_forward_far[i]=cam.forward[i];\n"
        "        p.light_pos_interval[i]=settings.case_id==A001Case::LightMotion?k.light_motion[i]:k.light_base[i];\n"
        "    }\n"
        "    p.camera_right_tan_x[3]=tan_y*(float(settings.tile_width)/float(settings.tile_height));\n"
        "    p.camera_up_tan_y[3]=tan_y;\n"
        "    return p;\n"
        "}\n\n")
    s = exactly_one(s, anchor, wrapper + anchor)
    return s


TRANSFORMS = {"n009_a001_scene.cpp": a001_scene, "n009_b002_scene.cpp": b002_scene, "n009_a001_runtime.cpp": a001_runtime}


def generate(root: Path, out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    result = {}
    for name, rel in FILES.items():
        raw = (root / rel).read_bytes()
        sha = hashlib.sha256(raw).hexdigest()
        text = header(TRANSFORMS[name](raw.decode("utf-8")), rel, sha)
        (out / name).write_text(text, encoding="utf-8")
        result[name] = {"source": rel, "source_sha256": sha}
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    print(generate(a.root, a.out))


if __name__ == "__main__":
    main()
