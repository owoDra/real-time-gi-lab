#!/usr/bin/env python3
"""Generate the N008 CPU-only frame-state exporter header by VERBATIM extraction
of the Renderer's own CPU code (no re-implementation of scene state).

Extracted from the pinned N-series sources:
  n001_runtime.cpp  anonymous-namespace helpers: fail, MovingSelection,
                    translated_geometry, deformed_primitives, deformed_geometry,
                    choose_moving_selection, choose_deforming_selection
  a001_runtime.cpp  V3 helpers and build_a001_params
The N002 topology-churn mutation lives inside a member function; the exporter
re-states it and this script asserts its exact source lines still exist.
Source SHA-256s are embedded so a drifted source is detectable."""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

N001 = "src/research/lane_n_end_to_end_renderer/n001_runtime.cpp"
A001 = "src/research/lane_n_end_to_end_renderer/imported/lane_a_split_rc/a001_runtime.cpp"
N002 = "src/research/lane_n_end_to_end_renderer/n002_runtime.cpp"

N001_ITEMS = [
    r"\[\[noreturn\]\] void fail\(const char\* message\) \{",
    r"struct MovingSelection \{",
    r"\[\[nodiscard\]\] std::vector<lane_b::Triangle> translated_geometry\(",
    r"\[\[nodiscard\]\] std::vector<lane_b::Triangle> deformed_primitives\(",
    r"\[\[nodiscard\]\] std::vector<lane_b::Triangle> deformed_geometry\(",
    r"\[\[nodiscard\]\] MovingSelection choose_moving_selection\(",
    r"\[\[nodiscard\]\] MovingSelection choose_deforming_selection\(",
]
A001_ITEMS = [r"struct V3 \{ float x\{\}, y\{\}, z\{\}; \};"] + [
    r"V3 add\(", r"V3 sub\(", r"V3 mul\(", r"float dot\(", r"V3 cross\(", r"float length\(", r"V3 normalize\(",
    r"A001ParamsGpu build_a001_params\(const SceneSurfaceSet& scene, const A001Settings& settings\) \{",
]
# Exact N002 churn lines re-stated by the exporter (must remain verbatim in source).
N002_LINES = [
    "const float amplitude = std::max(",
    "lane_b::b002_segment_size(impl_->b_scene) * 0.04F);",
    "if ((local & 1U) == 0U) {",
    "const float sign = ((local >> 1U) & 1U) == 0U ? 1.0F : -1.0F;",
    "const float scale = 1.0F + float(local % 5U) * 0.125F;",
    "triangle.v0.y += sign * amplitude * 0.50F * scale;",
    "triangle.v1.z += sign * amplitude * 0.35F * scale;",
    "triangle.v2.x -= sign * amplitude * 0.20F * scale;",
    "max_primitive_id + 1U +",
    "static_cast<std::uint32_t>(local);",
]


def extract(text: str, pattern: str) -> str:
    lines = text.splitlines()
    rx = re.compile(r"^" + pattern)
    starts = [i for i, l in enumerate(lines) if rx.match(l)]
    if len(starts) != 1:
        raise SystemExit(f"pattern {pattern!r} matched {len(starts)} lines")
    i = starts[0]
    if lines[i].rstrip().endswith("}") and lines[i].count("{") == lines[i].count("}"):
        return lines[i]  # one-line definition
    depth, out = 0, []
    for line in lines[i:]:
        out.append(line)
        depth += line.count("{") - line.count("}")
        if depth == 0 and "{" in "".join(out):
            if line.rstrip().endswith("};") or line.rstrip() == "}":
                return "\n".join(out)
    raise SystemExit(f"unterminated block for {pattern!r}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    root = Path(a.root)
    src = {p: (root / p).read_text() for p in (N001, A001, N002)}
    sha = {p: hashlib.sha256((root / p).read_bytes()).hexdigest() for p in src}
    n002_norm = [l.strip() for l in src[N002].splitlines()]
    for line in N002_LINES:
        if line not in n002_norm:
            raise SystemExit(f"N002 churn line drifted: {line!r}")
    parts = ["// GENERATED by scripts/research/n008_hdr_oracle/generate_state_exporter.py -- do not edit.",
             "#pragma once"]
    for p, h in sha.items():
        parts.append(f'// source {p} sha256 {h}')
    parts.append("namespace n008_extracted_a001 {\nusing namespace phos::gi::lane_a;")
    parts += [extract(src[A001], x) for x in A001_ITEMS]
    parts.append("}  // namespace n008_extracted_a001")
    parts.append("namespace n008_extracted_n001 {\nnamespace lane_a = phos::gi::lane_a;\n"
                 "namespace lane_b = phos::gi::research::lane_b;")
    parts += [extract(src[N001], x) for x in N001_ITEMS]
    parts.append("}  // namespace n008_extracted_n001")
    parts.append("inline constexpr const char* kN008ExtractedSources[][2] = {" +
                 ", ".join(f'{{"{p}", "{h}"}}' for p, h in sha.items()) + "};")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
